#!/usr/bin/env python3
"""Generate motes/markdown/src/entities.mo from the WHATWG entity list.

    python3 -I tools/gen_entities.py --entities entities.json --out src/entities.mo

Input:  https://html.spec.whatwg.org/entities.json
Output: one dispatcher over the first byte, then one linear `String.beq`
        chain per initial byte. The generated file is committed; the input
        is not vendored.
"""
import argparse
import hashlib
import json
import sys

URL = "https://html.spec.whatwg.org/entities.json"


def monad_string(value: str) -> str:
    out = []
    for ch in value:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\t":
            out.append("\\t")
        elif ord(ch) < 0x20:
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def emit_name_tree(fn, names, table):
    """A balanced tree over `names`, one function per node.

    A linear `else if` chain nests the expression once per name; the Rust
    host elaborates that on the stack, so a 300-name chain is a real risk in
    the whole-corpus check.
    """
    tree = _tree_names(names)
    nodes = []
    root = _flatten(tree, nodes)
    lines = []
    for idx, (spec, lid, rid) in enumerate(nodes):
        lines.append("#[partial]")
        lines.append("def %s_%d (name : String) : Option String :=" % (fn, idx))
        if spec[0] == "entry":
            lines.append("    if String.beq name %s then Option.some %s else %s"
                         % (monad_string(spec[1]), monad_string(table[spec[1]]),
                            _kid(fn, lid)))
            continue
        pivot = spec[1]
        lines.append("    if String.lt name %s then %s else %s"
                     % (monad_string(pivot), _kid(fn, lid), _kid(fn, rid)))
    lines.append("")
    lines.append("def %s (name : String) : Option String := %s_%d name" % (fn, fn, root))
    return lines


def _kid(fn, idx):
    return ("%s_%d name" % (fn, idx)) if idx is not None else "Option.none"


def _tree_names(names):
    if not names:
        return None
    if len(names) == 1:
        return ("entry", names[0], None, None, None)
    mid = len(names) // 2
    return ("node", names[mid], None,
            _tree_names(names[:mid]), _tree_names(names[mid:]))


def _flatten(tree, nodes):
    if tree is None:
        return None
    lid = _flatten(tree[3], nodes)
    rid = _flatten(tree[4], nodes)
    idx = len(nodes)
    nodes.append((tree, lid, rid))
    return idx


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--entities", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    raw = open(args.entities, "rb").read()
    digest = hashlib.sha256(raw).hexdigest()
    data = json.loads(raw)

    # Only the semicolon-terminated names are CommonMark entities.
    table = {}
    for key, entry in data.items():
        if not key.endswith(";"):
            continue
        name = key[1:-1]
        table[name] = entry["characters"]
    names = sorted(table)

    chunks = {}
    for name in names:
        first = name[0]
        chunks.setdefault(first, []).append(name)

    lines = []
    lines.append("// AUTO-GENERATED by tools/gen_entities.py -- do not edit.")
    lines.append("//")
    lines.append("// Source: %s" % URL)
    lines.append("// sha256(input) = %s" % digest)
    lines.append("// Names: %d (semicolon-terminated CommonMark entities)." % len(names))
    lines.append("//")
    lines.append("// One dispatcher over the first byte, then a linear `String.beq`")
    lines.append("// chain per initial byte. The chunk helpers are package-private.")
    lines.append("use init::string {}")
    lines.append("")
    lines.append("pub def Markdown.entity_count : I64 := %di64" % len(names))
    lines.append("")
    lines.append("pub def Markdown.entity_lookup (name : String) : Option String :=")
    lines.append("    match String.get name 0 {")
    lines.append("        Option.none => Option.none,")
    lines.append("        Option.some b =>")
    first = True
    for ch in sorted(chunks):
        cond = "if" if first else "else if"
        first = False
        lines.append('            %s U8.beq b %du8 then Markdown.entity_%s name'
                     % (cond, ord(ch), ch))
    lines.append("            else Option.none")
    lines.append("    }")
    lines.append("")

    for ch in sorted(chunks):
        lines.extend(emit_name_tree("Markdown.entity_%s" % ch, chunks[ch], table))
        lines.append("")

    text = "\n".join(lines)
    if args.check:
        current = open(args.out).read()
        if current != text:
            print("entities.mo is stale; regenerate", file=sys.stderr)
            return 1
        return 0
    with open(args.out, "w") as f:
        f.write(text)
    print("wrote %s: %d entities, %d initial-byte chunks" % (args.out, len(names), len(chunks)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
