#!/usr/bin/env bash
# Generate the web profile's JS glue (`wasm/web/web.js` by default) from
# `examples/gen_web_js.mo`, which renders `WebAbi.default` through
# `motes/web_wasm`'s `Glue.loader`.
#
# The file is a BUILD ARTIFACT, not a checked-in source: the generator is
# the only thing anyone may edit, so there is no drift to guard against.
# Every consumer must generate first -- `scripts/build-try.sh` (the /try
# deploy), `scripts/check-wasm-target.sh` and `scripts/check-try.sh` (the
# Node harnesses import `./web.js`).
#
# usage: scripts/gen-web-js.sh [out]
#   MONAD selects the compiler (like build-try.sh); otherwise the
#   tree-built binaries are tried (including `target-monad/release`, what
#   `scripts/build-self-hosted.sh` writes), then `monad`.
set -euo pipefail

root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
out="${1:-$root/wasm/web/web.js}"

if [ -n "${MONAD:-}" ]; then
    candidates=("$MONAD")
else
    candidates=()
    for candidate in "$root/target-monad/release/monad" \
                     "$root/target-monad/bootstrap-ci/monad" \
                     "$root/target-monad/ci-self-compile/monad" \
                     "$(command -v monad 2>/dev/null || true)"; do
        if [ -n "$candidate" ] && [ -x "$candidate" ]; then
            candidates+=("$candidate")
        fi
    done
    if [ "${#candidates[@]}" -eq 0 ]; then
        echo "gen-web-js: no compiler found; set MONAD or install one with 'monadup default'" >&2
        exit 1
    fi
fi

# `-o` leaves the `.ll`/`.o` intermediates beside its output, so build in a
# temp dir. The generator writes the JS to STDOUT; `monad run` would prepend
# its compile-status line, so the binary is built once and executed.
tmp="$(mktemp -d "${TMPDIR:-/tmp}/monad-gen-web-js.XXXXXX")"
trap 'rm -rf "$tmp"' EXIT

built=""
last_log=""
i=0
for monad in "${candidates[@]}"; do
    i=$((i + 1))
    log="$tmp/build-$i.log"
    echo "gen-web-js: trying compiler $monad" >&2
    if "$monad" build "$root/examples/gen_web_js.mo" \
            -o "$tmp/gen_web_js" --no-cache >"$log" 2>&1 \
        && [ -x "$tmp/gen_web_js" ] \
        && "$tmp/gen_web_js" >"$tmp/web.js" 2>>"$log"; then
        built="$monad"
        break
    fi
    last_log="$log"
    echo "gen-web-js: $monad cannot build the generator; trying the next compiler" >&2
done

if [ -z "$built" ]; then
    echo "gen-web-js: no compiler could build examples/gen_web_js.mo" >&2
    [ -n "$last_log" ] && cat "$last_log" >&2
    exit 1
fi

# Never trust an exit code alone (a stale compiler can emit an empty module):
# the output must carry the generated header, the import object and `start`.
fail() {
    echo "gen-web-js: the generated web.js is not the expected glue: $1" >&2
    exit 1
}
[ -s "$tmp/web.js" ] || fail "empty output"
grep -q '^// generated by web_wasm from WebAbi' "$tmp/web.js" \
    || fail "missing generated header"
grep -q '^export { imports };$' "$tmp/web.js" || fail "missing export { imports }"
grep -q '^export { start };$' "$tmp/web.js" || fail "missing export { start }"

mkdir -p "$(dirname "$out")"
cp "$tmp/web.js" "$out.tmp.$$"
mv "$out.tmp.$$" "$out"
echo "gen-web-js: compiler $built"
echo "gen-web-js: wrote $out"
